package proyecto1.proyecto2.lfp.AnalizadorLexico;

/**
 *
 * @author mario
 */
public class Token {
    
    private TokenTipos tipo;
    private String lexema;
    private int fila;
    private int columna;

    public Token(TokenTipos tipo, String lexema, int fila, int columna) {
        this.tipo = tipo;
        this.lexema = lexema;
        this.fila = fila;
        this.columna = columna;
    }

    public TokenTipos getTipo() {
        return tipo;
    }

    public void setTipo(TokenTipos tipo) {
        this.tipo = tipo;
    }

    public String getLexema() {
        return lexema;
    }

    public void setLexema(String lexema) {
        this.lexema = lexema;
    }

    public int getFila() {
        return fila;
    }

    public void setFila(int linia) {
        this.fila = linia;
    }

    public int getColumna() {
        return columna;
    }

    public void setColumna(int columna) {
        this.columna = columna;
    }
    
    
    
}
