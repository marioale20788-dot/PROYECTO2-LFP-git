package proyecto1.proyecto2.lfp.AnalizadorLexico.AST;

/**
 *
 * @author mario
 */
public class DirectivaNodo {
    private String tipo;
    private String valor;
     private int fila;
    private int columna;


   

    public DirectivaNodo(String tipo, String valor, int fila, int columna) {
        this.tipo = tipo;
        this.valor = valor;
        this.fila = fila;
        this.columna = columna;
    }

    public String getTipo() {
        return tipo;
    }

    public void setTipo(String tipo) {
        this.tipo = tipo;
    }

    public String getValor() {
        return valor;
    }

    public void setValor(String valor) {
        this.valor = valor;
    }

}
